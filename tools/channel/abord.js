// Order string of every ability on the map -> war3map.j between //ABORD_DATA_BEGIN and //ABORD_DATA_END (function CBS_OrdInit,
// hashtable HH, key SH_AbOrd). Channel (ANcl): DataF; other abilities: Order= of their base from the game data
// (w3x2lni data/*/mpq/Units/*abilityfunc.txt). Quick cast (CBS_QcOrd) reads only this table: GetAbilityOrderId crashed
// the game on passives / Channel (Game.dll+0xD6066, 15-17 Oct 2026).
//   node tools/channel/abord.js [w3x2lni dir]      (from the repo root; rewrites the block, idempotent)
const fs = require('fs');
const path = require('path');
const R = path.join(__dirname, '..', '..') + '/';
const W2L = process.argv[2] || 'C:/Users/Maksim/Downloads/w3x2lni_enUS_v2.7.2';
const dataDir = fs.readdirSync(W2L + '/data').map(d => W2L + '/data/' + d + '/mpq/Units').find(d => fs.existsSync(d));
const base = {};
for (const f of fs.readdirSync(dataDir).filter(f => /abilityfunc\.txt$/i.test(f))) {
  let sec = null;
  for (const l of fs.readFileSync(dataDir + '/' + f, 'latin1').replace(/\r/g, '').split('\n')) {
    const m = l.match(/^\[([A-Za-z0-9]{4})\]/); if (m) { sec = m[1]; continue; }
    const o = l.match(/^Order=([a-z0-9]+)\s*$/i); if (sec && o) base[sec] = o[1];
  }
}
const L = fs.readFileSync(R + 'table/ability.ini', 'utf8').replace(/^\uFEFF/, '').replace(/\r/g, '').split('\n');
const ab = {}; let sec = null, arr = null;
for (const l of L) {
  const m = l.match(/^\[([A-Za-z0-9]{4})\]$/);
  if (m) { sec = ab[m[1]] = {}; arr = null; continue; }
  if (!sec) continue;
  if (arr) { if (l === '}') arr = null; else sec[arr].push(l.replace(/[",]/g, '').trim()); continue; }
  const k = l.match(/^(_parent|DataF) = (.*)$/); if (!k) continue;
  const v = k[2];
  if (v === '{') { arr = k[1]; sec[arr] = []; continue; }
  sec[k[1]] = v.startsWith('{') ? v.slice(1, -1).split(',').map(s => s.trim().replace(/"/g, '')) : [v.replace(/"/g, '')];
}
const out = {};
for (const id of Object.keys(base)) out[id] = base[id];
for (const id of Object.keys(ab)) {
  const o = ab[id], p = o._parent && o._parent[0];
  if (p === 'ANcl') { const d = o.DataF && o.DataF[0]; if (d && /^[a-z0-9]+$/i.test(d)) out[id] = d; else delete out[id]; continue; }
  if (p && base[p]) out[id] = base[p];
}
const lines = Object.keys(out).sort().map(id => `call SaveStr(HH,SH_AbOrd,'${id}',"${out[id]}")`);
const J = R + 'map/war3map.j';
const j0 = fs.readFileSync(J, 'latin1');
const B = '//ABORD_DATA_BEGIN', E = '//ABORD_DATA_END';
const a = j0.indexOf(B), b = j0.indexOf(E);
if (a < 0 || b < a) throw new Error('markers not found');
const body = [B + ' -- generated by tools/channel/abord.js (order of every ability: Channel DataF, others the base Order), do not edit',
  'function CBS_OrdInit takes nothing returns nothing', ...lines, 'endfunction', ''].join('\r\n');
fs.writeFileSync(J, j0.slice(0, a) + body + j0.slice(b), 'latin1');
console.log('abilities with order:', lines.length, 'base orders:', Object.keys(base).length);
