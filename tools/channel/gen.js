// Channel (ANcl) order and target type by ability id -> war3map.j between //SHNCHAN_DATA_BEGIN and //SHNCHAN_DATA_END
// (function ShinjiChanInit). GetAbilityBaseStringLevelFieldById(..Ncl6..) returns "Default String" in game, so Hirako T
// (forced cast) reads the order from this table. Run after adding or changing Channel abilities:
//   node tools/channel/gen.js            (from the repo root; rewrites the block, idempotent)
const fs = require('fs');
const path = require('path');
const R = path.join(__dirname, '..', '..') + '/';
const L = fs.readFileSync(R + 'table/ability.ini', 'utf8').replace(/^﻿/, '').replace(/\r/g, '').split('\n');
const ab = {}; let sec = null, arr = null;
for (const l of L) {
  const m = l.match(/^\[([A-Za-z0-9]{4})\]$/);
  if (m) { sec = ab[m[1]] = {}; arr = null; continue; }
  if (!sec) continue;
  if (arr) { if (l === '}') arr = null; else sec[arr].push(l.replace(/[",]/g, '').trim()); continue; }
  const k = l.match(/^(_parent|DataF|DataB) = (.*)$/); if (!k) continue;
  const v = k[2];
  if (v === '{') { arr = k[1]; sec[arr] = []; continue; }
  sec[k[1]] = v.startsWith('{') ? v.slice(1, -1).split(',').map(s => s.trim().replace(/"/g, '')) : [v.replace(/"/g, '')];
}
const lines = [];
for (const id of Object.keys(ab).sort()) {
  const o = ab[id];
  if (!o._parent || o._parent[0] !== 'ANcl' || !o.DataF || !o.DataF[0]) continue;
  const ord = o.DataF[0];
  if (!/^[a-z0-9]+$/i.test(ord)) continue;
  const tt = parseInt((o.DataB && o.DataB[0]) || '0', 10) || 0;
  lines.push(`call SaveStr(HH,SH_ShnChanO,'${id}',"${ord}")`);
  if (tt) lines.push(`call SaveInteger(HH,SH_ShnChanT,'${id}',${tt})`);
}
const J = R + 'map/war3map.j';
const j0 = fs.readFileSync(J, 'latin1');
const B = '//SHNCHAN_DATA_BEGIN', E = '//SHNCHAN_DATA_END';
const a = j0.indexOf(B), b = j0.indexOf(E);
if (a < 0 || b < a) throw new Error('markers not found');
const body = [B + ' -- generated by tools/channel/gen.js from table/ability.ini (Channel: Ncl6 order, target type), do not edit',
  'function ShinjiChanInit takes nothing returns nothing', ...lines, 'endfunction', ''].join('\r\n');
fs.writeFileSync(J, j0.slice(0, a) + body + j0.slice(b), 'latin1');
console.log('channel abilities:', lines.filter(l => l.includes('SaveStr')).length);
